fn block(h: &mut [u32; 8], b: &[u8; 64]) {
    let mut w = [0u32; 64];
    for (w, c) in w.iter_mut().zip(b.as_chunks::<4>().0) {
        *w = u32::from_be_bytes(*c);
    }
    for i in 16..64 {
        let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
        let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
    }
    let mut v = *h;
    for i in 0..64 {
        let s1 = v[4].rotate_right(6) ^ v[4].rotate_right(11) ^ v[4].rotate_right(25);
        let ch = (v[4] & v[5]) ^ (!v[4] & v[6]);
        let t1 = v[7].wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
        let s0 = v[0].rotate_right(2) ^ v[0].rotate_right(13) ^ v[0].rotate_right(22);
        let maj = (v[0] & v[1]) ^ (v[0] & v[2]) ^ (v[1] & v[2]);
        v.copy_within(0..7, 1);
        v[4] = v[4].wrapping_add(t1);
        v[0] = t1.wrapping_add(s0.wrapping_add(maj));
    }
    for (h, v) in h.iter_mut().zip(v) {
        *h = h.wrapping_add(v);
    }
}

/// Lowercase hex digest of everything in `r`.
pub fn hex(r: &mut impl Read) -> std::io::Result<String> {
    let mut h = [0x6a09e667u32, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19];
    let mut len = 0u64;
    let mut buf = vec![0u8; 64 * 1024];
    loop {
        // fill the buffer, so only the last round is short
        let mut n = 0;
        while n < buf.len() {
            match r.read(&mut buf[n..]) {
                Ok(0) => break,
                Ok(k) => n += k,
                Err(e) if e.kind() == std::io::ErrorKind::Interrupted => {}
                Err(e) => return Err(e),
            }
        }
        len += n as u64;
        if n == buf.len() {
            buf.as_chunks::<64>().0.iter().for_each(|b| block(&mut h, b));
            continue;
        }
        let mut tail = buf[..n].to_vec();
        tail.push(0x80);
        tail.resize((tail.len() + 8).next_multiple_of(64) - 8, 0);
        tail.extend((len * 8).to_be_bytes());
        tail.as_chunks::<64>().0.iter().for_each(|b| block(&mut h, b));
        return Ok(h.iter().map(|w| format!("{w:08x}")).collect());
    }
}

#[cfg(test)]
mod tests {
    use super::hex;

    #[test]
    fn vectors() {
        let h = |b: &[u8]| hex(&mut &b[..]).unwrap();
        assert_eq!(h(b""), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
        assert_eq!(h(b"abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        assert_eq!(
            h(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
        // past one read buffer
        assert_eq!(h(&vec![b'a'; 1_000_000]), "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0");
        assert_eq!(h(&vec![0; 65536]).len(), 64);
    }
}
