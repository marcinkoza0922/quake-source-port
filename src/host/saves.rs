use super::*;

impl Host {
    /// Writes the pending screenshot and/or save thumbnail from the captured
    /// frame. When the renderer is still reading it back (wgpu in the
    /// browser), both stay pending and this runs again next frame.
    pub(super) fn write_captures(&mut self) {
        if !self.wants_capture() { return; }
        let captured = self.r.take_capture();
        if matches!(captured, Ok(None)) {
            self.capture_frame(None);
            return;
        }
        if let Ok(Some((w, h, px))) = &captured {
            self.capture_frame(Some((*w, *h, px)));
        }
        if self.screenshot.is_none() && self.thumb.is_none() { return; }
        let (shot, thumb) = (self.screenshot.take(), self.thumb.take());
        self.clean_shot = false;
        let (w, h, px) = match captured {
            Ok(c) => c.expect("pending returned above"),
            Err(e) => return self.con.print(&qcore::ctr!("screenshot failed: {}\n", format!("{e:?}"))),
        };
        if let Some(name) = shot {
            self.write_screenshot(&name, w, h, &px);
        }
        if let Some(path) = thumb {
            self.write_thumb(&path, w, h, &px);
        }
    }

    fn write_screenshot(&mut self, name: &str, w: u32, h: u32, px: &[u8]) {
        {
            {
                let png = crate::png::encode_rgba(w, h, px);
                let path = if name.is_empty() {
                    let dir = self.user_dir();
                    (0..10000).map(|i| dir.join(format!("spasm{i:04}.png"))).find(|p| !qcore::vfs::exists(p)).unwrap_or(dir.join("spasm.png"))
                } else {
                    let p = PathBuf::from(name);
                    if p.extension().is_none() { p.with_extension("png") } else { p }
                };
                match qcore::vfs::write(&path, &png) {
                    Ok(()) => self.con.print(&qcore::ctr!("Wrote {}\n", path.display())),
                    Err(e) => self.con.print(&qcore::ctr!("screenshot: {}\n", e)),
                }
            }
        }
    }

    /// Writes config.cfg (bindings + archived cvars) in the active gamedir.
    pub fn write_config(&mut self) {
        // Headless runs are tests/tools; never clobber the user's config.
        if self.headless {
            return;
        }
        self.write_global_config();
        let dir = self.user_dir();
        let mut s = String::from("// generated by quake-source-port, do not modify\n");
        for l in self.input.archive_bindings() {
            s += &l;
            s.push('\n');
        }
        for l in self.server.core.cvars.archive_lines() {
            s += &l;
            s.push('\n');
        }
        if let Err(e) = qcore::vfs::write(&dir.join("config.cfg"), s.as_bytes()) {
            eprintln!("couldn't write config.cfg: {e}");
        }
        self.con.save_history(&crate::user_dir("id1"));
    }

    /// Per-game user data dir (config, saves, screenshots); never the game data dir.
    pub fn user_dir(&self) -> PathBuf {
        crate::user_dir(self.fs_snapshot.1.last().map_or("id1", String::as_str))
    }

    /// Switches the active user data directory (optionally copying existing
    /// user data first) and updates live filesystem, config and mod state.
    pub(super) fn apply_user_data_dir(&mut self, parent: PathBuf, copy: bool) {
        let old_root = crate::userdata::root();
        let target_root = crate::userdata::resolve_root(&parent);
        if copy
            && let Err(e) = crate::userdata::copy_data(&old_root, &target_root)
        {
            self.print(&qcore::ctr!("User data directory error: {}\n", e));
            return;
        }
        let root = match crate::userdata::set_parent(&parent, !self.headless) {
            Ok(r) => r,
            Err(e) => {
                self.print(&qcore::ctr!("User data directory error: {}\n", e));
                return;
            }
        };
        // Drop any startup `-userdir <path>` so mod relaunches use the new choice.
        let mut cleaned = Vec::with_capacity(self.cmdline.len());
        let mut it = self.cmdline.iter();
        while let Some(a) = it.next() {
            if a.eq_ignore_ascii_case("-userdir") {
                it.next();
            } else {
                cleaned.push(a.clone());
            }
        }
        self.cmdline = cleaned;
        self.server.core.fs.set_mod_roots(vec![crate::user_mods_dir()]);
        self.server.core.fs.replace_user_dir(self.user_dir());
        self.con.shell_env.userdir = self.user_dir();
        self.save_thumbs.clear();
        self.write_config();
        self.scan_mods();
        self.refresh_soundtracks();
        self.print(&qcore::ctr!("User data directory set to {}\n", root.display()));
    }

    /// Where a save called `name` is written: `.qsa` for a game with
    /// add-ons (no other port can load it), `.sav` otherwise.
    pub(super) fn savegame_path(&self, name: &str) -> PathBuf {
        self.user_dir().join(format!("{}.{}", save_stem(name), crate::autosave::ext(self.server.qsa_saves())))
    }

    /// The existing save called `name`, in either format.
    /// Falls back to the 2021 re-release's save folder (like ironwail),
    /// taking only a KEX save made for the running game.
    pub(super) fn find_save(&self, name: &str) -> Option<PathBuf> {
        let dir = self.user_dir();
        let own = match name.rsplit_once('.') {
            Some((_, e)) if e == crate::autosave::SAVE_EXT || e == crate::autosave::ADDON_EXT => qcore::vfs::is_file(&dir.join(name)).then(|| dir.join(name)),
            _ => crate::autosave::find(&dir, name),
        };
        own.or_else(|| self.find_other_engine_save(name))
    }

    /// A plain save another engine left for the running game, in
    /// [`Self::external_saves`] order.
    fn find_other_engine_save(&self, name: &str) -> Option<PathBuf> {
        if !valid_save_name(name) {
            return None;
        }
        let file = format!("{}.sav", save_stem(name));
        self.external_save_dirs().into_iter().map(|(d, _)| d.join(&file)).find(|p| self.external_save_ok(p))
    }

    /// Folders where other engines leave saves for the running game:
    /// vkQuake and QuakeSpasm write `<basedir>/<game>/`, ironwail
    /// `~/.ironwail/<game>/`, the 2021 re-release its own save folder (for
    /// every game, so its saves are checked for this game's dir).
    fn external_save_dirs(&self) -> Vec<(PathBuf, crate::menu::SaveSource)> {
        use crate::menu::SaveSource;
        let fs = &self.server.core.fs;
        let game = fs.game_dir().unwrap_or("id1");
        let mut dirs = vec![(fs.basedir().join(game), SaveSource::GameDir)];
        if let Some(home) = std::env::var_os("HOME") {
            dirs.push((PathBuf::from(home).join(".ironwail").join(game), SaveSource::Ironwail));
        }
        dirs.extend(qcore::fs::kex_save_dirs().into_iter().map(|d| (d, SaveSource::Kex)));
        dirs
    }

    /// A file in [`Self::external_save_dirs`] that is a save of the running
    /// game: a KEX save names its game dir on line 2 (version 6).
    fn external_save_ok(&self, p: &std::path::Path) -> bool {
        let Ok(b) = qcore::vfs::read(p) else { return false };
        let mut lines = b.split(|&c| c == b'\n').map(|l| String::from_utf8_lossy(l).trim().to_ascii_lowercase());
        match lines.next().as_deref() {
            Some("5") => true,
            Some("6") => {
                let game = self.server.core.fs.game_dir().unwrap_or("id1").to_ascii_lowercase();
                lines.next().as_deref() == Some(game.as_str())
            }
            _ => false,
        }
    }

    /// Saves other engines left for this game, first folder winning a name.
    fn external_saves(&self) -> Vec<crate::menu::SaveSlot> {
        let mut seen = std::collections::HashSet::new();
        let mut out = Vec::new();
        for (dir, source) in self.external_save_dirs() {
            let Ok(entries) = qcore::vfs::read_dir(&dir) else { continue };
            let mut files: Vec<_> = entries.into_iter().filter(|e| !e.is_dir).map(|e| e.path).collect();
            files.sort();
            for path in files {
                let Some(name) = path.file_stem().and_then(|n| n.to_str()).map(str::to_owned) else { continue };
                if !path.extension().is_some_and(|e| e.eq_ignore_ascii_case("sav")) || !valid_save_name(&name) {
                    continue;
                }
                let Ok(bytes) = qcore::vfs::read(&path) else { continue };
                let text = qcore::text::decode(&bytes);
                if !self.external_save_ok(&path) || !seen.insert(name.to_ascii_lowercase()) {
                    continue;
                }
                let Some(info) = crate::saveinfo::SaveInfo::parse(&text, qcore::vfs::modified(&path).ok()) else { continue };
                out.push(crate::menu::SaveSlot { name, info, thumb: None, source });
            }
        }
        out
    }

    pub(super) fn update_autosave(&mut self) {
        if self.dedicated || self.demo.is_some() || self.local.is_none()
            || !self.server.active() || self.server.core.maxclients() != 1
            || self.server.core.cvars.value_of("deathmatch") != 0.0
            || self.cl.signon != 4 || self.cl.intermission != 0
            || self.cl.stats[STAT_HEALTH] <= 0 || self.menu.active() || self.server.core.sv.paused {
            return;
        }
        let cv = &self.server.core.cvars;
        let on = cv.value_of("sv_autosave") != 0.0;
        let keep = if on { cv.value_of("sv_autosave_keep").clamp(0.0, crate::autosave::MAX as f32) as usize } else { 0 };
        let flags = ["entry", "secret", "monsters", "secrets", "key"].map(|n| cv.value_of(&format!("sv_autosave_{n}")) != 0.0);
        let interval = cv.value_of("sv_autosave_interval").max(0.0) as f64 * 60.0;
        let reason = self.autosave.update(self.server.time(), self.server.stats(), self.server.player_keys(), self.server.core.sv.loadgame, flags, interval);
        if let Some(reason) = reason.filter(|_| keep > 0) {
            let text = self.server.save_game();
            // The v5 description is ignored by the loader; preserve the trigger in the save itself.
            let text = qserver::addons::save::set_comment(&text, &format!("AUTOSAVE_{}", reason.replace(' ', "_")));
            match crate::autosave::rotate(&self.user_dir(), keep, &text, crate::autosave::ext(self.server.qsa_saves())) {
                Ok(()) => {
                    self.print(&qcore::ctr!("Autosaved.\n"));
                    self.thumb = Some(self.user_dir().join(format!("autosave0.{}", crate::autosave::THUMB_EXT)));
                }
                Err(e) => self.print(&qcore::ctr!("ERROR: autosave failed: {}\n", e)),
            }
        }
    }

    /// Fills the Load/Save list from the user dir, newest first.
    pub(super) fn scan_saves(&mut self) {
        self.menu.save_inventory = crate::save_inventory::Inventory::new(self.fs(), crate::sbar::Pack::from_game_dirs(self.fs_snapshot.1.iter().map(String::as_str)));
        let dir = self.user_dir();
        self.menu.save_pb = crate::menu::SavePb {
            stats: qui::stats::Stats::load(&dir),
            prefer_full: self.cv("hud_pb_100") != 0.0,
            color: crate::reticle::color_of(&self.server.core.cvars, "hud_pb_color"),
        };
        let mut all: Vec<crate::menu::SaveSlot> = qcore::vfs::read_dir(&dir).into_iter().flatten().filter_map(|entry| {
            let path = entry.path;
            if !matches!(path.extension()?.to_str()?, crate::autosave::SAVE_EXT | crate::autosave::ADDON_EXT) { return None; }
            let name = path.file_stem()?.to_str()?.to_owned();
            if !valid_save_name(&name) { return None; }
            let modified = qcore::vfs::modified(&path).ok();
            let info = crate::saveinfo::SaveInfo::parse(&qcore::text::decode(&qcore::vfs::read(&path).ok()?), modified)?;
            Some(crate::menu::SaveSlot { name, info, thumb: None, source: crate::menu::SaveSource::Own })
        }).collect();
        all.sort_by(|a, b| b.info.modified.cmp(&a.info.modified).then_with(|| a.name.cmp(&b.name)));
        // a name in both formats is one save: the newer file wins
        let mut seen = std::collections::HashSet::new();
        all.retain(|s| seen.insert(s.name.to_ascii_lowercase()));
        // every name of ours, autosaves too: `load` would find ours first
        for s in &mut all {
            s.thumb = self.save_thumb(&dir, &s.name);
        }
        let latest = all.first().cloned();
        let autos = self.menu.autosaves && self.menu.screen == Screen::Load;
        all.retain(|s| s.is_autosave() == autos);
        if self.menu.screen == Screen::Load && !autos
            && let Some(l) = &latest
        {
            all.retain(|s| s.name != l.name);
        }
        // Load also lists what other engines saved for this game (`load`
        // finds them by name, so ours win a shared name)
        if self.menu.screen == Screen::Load && !autos {
            let ours = all.len();
            all.extend(self.external_saves().into_iter().filter(|s| !seen.contains(&s.name.to_ascii_lowercase())));
            all[ours..].sort_by(|a, b| b.info.modified.cmp(&a.info.modified).then_with(|| a.name.cmp(&b.name)));
        }
        self.menu.saves = all;
        self.menu.latest = latest;
        self.menu.clamp_save_cursor();
    }

    /// Thumbnail picture of save `name` (`<name>.thumb`), uploaded once per file version.
    fn save_thumb(&mut self, dir: &std::path::Path, name: &str) -> Option<(qrender::PicId, u32, u32)> {
        let path = dir.join(format!("{name}.{}", crate::autosave::THUMB_EXT));
        let modified = qcore::vfs::modified(&path).ok()?;
        let key = name.to_ascii_lowercase();
        if let Some((id, t)) = self.save_thumbs.get(&key) && *t == modified {
            return Some((*id, THUMB_W, THUMB_H));
        }
        let data = qcore::vfs::read(&path).ok()?;
        let rgba = read_thumb(&data)?;
        let id = match self.save_thumbs.get(&key) {
            Some(&(id, _)) => { self.r.update_pic(id, rgba).ok()?; id }
            None => self.r.register_pic_rgba_linear(THUMB_W, THUMB_H, rgba).ok()?,
        };
        self.save_thumbs.insert(key, (id, modified));
        Some((id, THUMB_W, THUMB_H))
    }

    /// Writes the thumbnail of a save from a captured frame.
    pub(super) fn write_thumb(&mut self, path: &std::path::Path, w: u32, h: u32, px: &[u8]) {
        let data = encode_thumb(w, h, px);
        if let Err(e) = qcore::vfs::write(path, &data) {
            self.con.print(&qcore::ctr!("couldn't write {}: {}\n", path.display(), e));
        }
    }
}

/// Save thumbnails: 160x90 RGBA after an 8-byte header ("QTHB", w, h as u16 LE).
const THUMB_W: u32 = 160;
const THUMB_H: u32 = 90;

/// Box-filters a frame down to the thumbnail size (cropped to 16:9).
fn encode_thumb(w: u32, h: u32, px: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(8 + (THUMB_W * THUMB_H * 4) as usize);
    out.extend_from_slice(b"QTHB");
    out.extend_from_slice(&(THUMB_W as u16).to_le_bytes());
    out.extend_from_slice(&(THUMB_H as u16).to_le_bytes());
    // crop the source to 16:9 around its centre
    let (cw, ch) = if w * 9 > h * 16 { (h * 16 / 9, h) } else { (w, w * 9 / 16) };
    let (x0, y0) = ((w - cw) / 2, (h - ch) / 2);
    for ty in 0..THUMB_H {
        let (sy0, sy1) = (y0 + ty * ch / THUMB_H, (y0 + (ty + 1) * ch / THUMB_H).max(y0 + ty * ch / THUMB_H + 1));
        for tx in 0..THUMB_W {
            let (sx0, sx1) = (x0 + tx * cw / THUMB_W, (x0 + (tx + 1) * cw / THUMB_W).max(x0 + tx * cw / THUMB_W + 1));
            let mut sum = [0u32; 3];
            let mut n = 0;
            for sy in sy0..sy1.min(h) {
                for sx in sx0..sx1.min(w) {
                    let i = ((sy * w + sx) * 4) as usize;
                    if let Some(p) = px.get(i..i + 3) {
                        for k in 0..3 { sum[k] += u32::from(p[k]); }
                        n += 1;
                    }
                }
            }
            let n = n.max(1);
            out.extend_from_slice(&[(sum[0] / n) as u8, (sum[1] / n) as u8, (sum[2] / n) as u8, 255]);
        }
    }
    out
}

fn read_thumb(data: &[u8]) -> Option<&[u8]> {
    let size = (THUMB_W * THUMB_H * 4) as usize;
    (data.get(..4)? == b"QTHB" && data.get(4..8)? == [THUMB_W as u8, 0, THUMB_H as u8, 0]).then_some(())?;
    data.get(8..8 + size)
}

/// Save names the menu offers: no path parts or characters that break a command.
fn valid_save_name(name: &str) -> bool {
    !name.is_empty() && !name.chars().any(|c| c.is_control() || matches!(c, '"' | ';' | '\\' | '/' | ':'))
        && name != "." && name != ".."
}

/// A save name without a `.sav`/`.qsa` extension.
fn save_stem(name: &str) -> &str {
    name.strip_suffix(".sav").or_else(|| name.strip_suffix(".qsa")).unwrap_or(name)
}

pub(super) fn register(c: &mut Commands<Host>) {
    c.add("menu_load", |h, _| {
        h.menu.autosaves = false;
        h.menu.open(Screen::Load);
        h.scan_saves();
    });
    c.add("menu_autosaves", |h, _| {
        h.menu.autosaves = true;
        h.menu.open(Screen::Load);
        h.scan_saves();
    });
    c.add("menu_save", |h, _| {
        h.menu.autosaves = false;
        if h.server.active() {
            h.menu.open(Screen::Save);
            h.scan_saves();
        }
    });
    c.add("_scansaves", |h, _| h.scan_saves());
    c.add("menu_dirbrowser", |h, _| h.menu.open_dir_browser());
    c.add("_apply_user_data_dir", |h, _| {
        if let Some((parent, copy)) = h.menu.pending_user_data_dir.take() {
            h.apply_user_data_dir(parent, copy);
        }
    });
    c.add("_deletesave", |h, a| {
        let name = a.argv(1);
        if !valid_save_name(name) { return; }
        let dir = h.user_dir();
        let _ = crate::autosave::remove_other_exts(&dir, name, None);
        let _ = qcore::vfs::remove_file(&dir.join(format!("{name}.{}", crate::autosave::THUMB_EXT)));
        h.scan_saves();
    });
    c.add("save", |h, a| {
        if a.argc() != 2 {
            h.print("save <savename> : save a game\n");
            return;
        }
        if !h.server.active() || h.cl.intermission != 0 || h.server.any_client_dead() {
            h.print(&qcore::ctr!("Can't save now.\n"));
            return;
        }
        if qserver::modifiers::value(&h.server.core, "modifier_nosaves") != 0.0 {
            h.print(&qcore::ctr!("This game only autosaves (No Manual Saves modifier).\n"));
            return;
        }
        let text = h.server.save_game();
        let p = h.savegame_path(a.argv(1));
        match qcore::vfs::write(&p, &qcore::text::encode(&text)) {
            Ok(()) => {
                // the slot is one save: drop a same-named file of the other format
                if let (Some(d), Some(stem)) = (p.parent(), p.file_stem().and_then(|s| s.to_str())) {
                    let _ = crate::autosave::remove_other_exts(d, stem, p.extension().and_then(|e| e.to_str()));
                }
                h.print(&qcore::ctr!("Game saved.\n"));
                h.thumb = Some(p.with_extension(crate::autosave::THUMB_EXT));
            }
            Err(e) => h.print(&qcore::ctr!("ERROR: couldn't write {}: {}\n", p.display(), e)),
        }
    });
    c.add("load", |h, a| {
        if a.argc() != 2 {
            h.print("load <savename> : load a game\n");
            return;
        }
        let Some(p) = h.find_save(a.argv(1)) else {
            h.print(&qcore::ctr!("ERROR: couldn't open {}\n", h.savegame_path(a.argv(1)).display()));
            return;
        };
        let Ok(bytes) = qcore::vfs::read(&p) else {
            h.print(&qcore::ctr!("ERROR: couldn't open {}\n", p.display()));
            return;
        };
        let text = qcore::text::decode(&bytes);
        h.print(&qcore::ctr!("Loading {}...\n", save_stem(a.argv(1))));
        if let Some(i) = h.local.take() {
            h.server.drop_client(i, false);
        }
        h.disconnect_client();
        if let Err(e) = h.server.load_game(&text) {
            h.print(&qcore::ctr!("load failed: {}\n", e));
        }
        h.drain_server_log();
    });
}
